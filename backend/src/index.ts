import 'express-async-errors';
import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import crypto from 'node:crypto';
import { logger } from './config/logger';
import pinoHttp from 'pino-http';
import rateLimit from 'express-rate-limit';
import cookieParser from 'cookie-parser';
import { configureAdvancedApi } from './routes/advanced';
import { startNotificationWorker } from './services/notificationQueue';
import Redis from 'ioredis';
import { pool } from './config/db';
import { configureApi } from './routes/api';
import { configureAdminApi } from './routes/admin';
import { errorHandler, notFoundHandler } from './middleware/errors';
import { seedDatabase } from './services/seed';

const app=express();
const frontendOrigin=process.env.FRONTEND_ORIGIN || 'http://localhost:3000';
const redis=new Redis(process.env.REDIS_URL || 'redis://localhost:6379', {lazyConnect:true, maxRetriesPerRequest:1});
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin:frontendOrigin,credentials:true,methods:['GET','POST','PUT','PATCH','DELETE','OPTIONS'],allowedHeaders:['Content-Type','Authorization','X-Request-Id']}));
app.use(pinoHttp({logger,genReqId:(req,res)=>{const incoming=req.headers['x-request-id'];const id=typeof incoming==='string' && /^[a-zA-Z0-9._-]{1,100}$/.test(incoming)?incoming:crypto.randomUUID();res.setHeader('X-Request-Id',id);return id;}}));
app.use(express.json({limit:'1mb',verify:(req:any,_res,buf)=>{req.rawBody=Buffer.from(buf)}}));
app.use(cookieParser());
app.use('/api', rateLimit({windowMs: 60_000, limit: 120, standardHeaders: 'draft-7', legacyHeaders: false, message: {error:'Too many requests. Please retry shortly.'}}));
app.use('/api/auth', rateLimit({windowMs: 60_000, limit: 10, standardHeaders: 'draft-7', legacyHeaders: false, message: {error:'Too many authentication requests. Please retry shortly.'}}));
app.get('/health',(_req,res)=>res.json({ok:true,service:'skymate-api'}));
app.get('/metrics',(_req,res)=>{res.type('text/plain; version=0.0.4').send('# HELP skymate_api_up API process readiness\n# TYPE skymate_api_up gauge\nskymate_api_up 1\n');});
app.get('/ready',async(_req,res)=>{try{await pool.query('SELECT 1');await redis.ping();res.json({ok:true,database:'ready',redis:'ready'});}catch{res.status(503).json({ok:false,dependencies:'mysql_or_redis_unavailable'});}});
app.use(configureApi({pool,redis}));
app.use(configureAdvancedApi({pool,redis}));
app.use(configureAdminApi(pool));
app.use(notFoundHandler);
app.use(errorHandler);
const port=Number(process.env.PORT || 4000);
async function start(){try{await pool.query('SELECT 1');await redis.connect();await seedDatabase(pool);startNotificationWorker(pool);logger.info('Database seed check completed');app.listen(port,'0.0.0.0',()=>logger.info({port},'SkyMate API listening'));}catch(error){logger.error({err:error},'Startup dependency check failed');process.exit(1);}}
void start();
